using sdbusplus::xyz::openbmc_project::Common::Error::InternalFailure;
using stdplus::fd::Fd;

void Pattern::writePattern(const uint64_t driveSize, Fd& fd)
{
    uint64_t currentIndex = 0;

    // The pseudo-random sequence is determined by the seed such that it can
    // be regenerated by verifyPattern(). NOLINTNEXTLINE
    std::mt19937_64 generator(seed);
    std::array<uint64_t, blockSizeUsing64> randArr{};

    while (currentIndex < driveSize)
    {
        // generate a 4k block of prng
        for (auto& word : randArr)
        {
            word = generator();
        }
        auto randBytes = std::as_bytes(std::span{randArr});
        // if we can write all 4k bytes do that, else write the remainder
        size_t writeSize = currentIndex + blockSize < driveSize
                               ? blockSize
                               : driveSize - currentIndex;
        try
        {
            size_t written = 0;
            size_t retry = 0;
            while (written < writeSize)
            {
                written +=
                    fd.write(randBytes.subspan(written, writeSize - written))
                        .size();
                if (written == writeSize)
                {
                    break;
                }
                if (written > writeSize)
                {
                    throw InternalFailure();
                }
                retry++;
                if (retry > maxRetry)
                {
                    lg2::error("Unable to do full write", "REDFISH_MESSAGE_ID",
                               std::string("eStorageD.1.0.EraseFailure"));
                    throw InternalFailure();
                }
                std::this_thread::sleep_for(delay);
            }
        }
        catch (...)
        {
            lg2::error("Estoraged erase pattern unable to write",
                       "REDFISH_MESSAGE_ID",
                       std::string("eStorageD.1.0.EraseFailure"));
            throw InternalFailure();
        }
        currentIndex = currentIndex + writeSize;
    }
}

void Pattern::verifyPattern(const uint64_t driveSize, Fd& fd)
{
    uint64_t currentIndex = 0;
    // Regenerate the pseudo-random sequence written by writePattern().
    // NOLINTNEXTLINE
    std::mt19937_64 generator(seed);
    std::array<uint64_t, blockSizeUsing64> randArr{};
    std::array<std::byte, blockSize> readArr{};

    while (currentIndex < driveSize)
    {
        size_t readSize = currentIndex + blockSize < driveSize
                              ? blockSize
                              : driveSize - currentIndex;
        try
        {
            for (auto& word : randArr)
            {
                word = generator();
            }
            size_t read = 0;
            size_t retry = 0;
            while (read < readSize)
            {
                read +=
                    fd.read(std::span{readArr}.subspan(read, readSize - read))
                        .size();
                if (read == readSize)
                {
                    break;
                }
                if (read > readSize)
                {
                    throw InternalFailure();
                }
                retry++;
                if (retry > maxRetry)
                {
                    lg2::error("Unable to do full read", "REDFISH_MESSAGE_ID",
                               std::string("eStorageD.1.0.EraseFailure"));
                    throw InternalFailure();
                }
                std::this_thread::sleep_for(delay);
            }
        }
        catch (...)
        {
            lg2::error("Estoraged erase pattern unable to read",
                       "REDFISH_MESSAGE_ID",
                       std::string("eStorageD.1.0.EraseFailure"));
            throw InternalFailure();
        }

        if (!std::ranges::equal(
                std::as_bytes(std::span{randArr}).subspan(0, readSize),
                std::span{readArr}.subspan(0, readSize)))
        {
            lg2::error("Estoraged erase pattern does not match",
                       "REDFISH_MESSAGE_ID",
                       std::string("eStorageD.1.0.EraseFailure"));
            throw InternalFailure();
        }
        currentIndex = currentIndex + readSize;
    }
}

